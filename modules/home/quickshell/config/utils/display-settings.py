#!/usr/bin/env python3
"""Persist display preferences without modifying the shared machine configuration."""
import fcntl
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time

ROOT = Path(os.environ.get('XDG_STATE_HOME', Path.home() / '.local/state')) / 'quickshell'
HYPRCTL = os.environ.get('HYPRCTL', 'hyprctl')


def read():
    try:
        return json.loads((ROOT / 'display.json').read_text())
    except (FileNotFoundError, ValueError):
        return {'monitors': {}, 'night': {'enabled': False, 'temperature': 4000}}


def atomic(path, text):
    ROOT.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', dir=ROOT, delete=False) as f:
        f.write(text)
        temporary = f.name
    os.replace(temporary, path)


def lua_string(value):
    return '"' + ''.join('\\%03d' % b for b in value.encode()) + '"'


def monitor_rule(name, prefs):
    output = lua_string(name)
    resolution = lua_string(prefs['resolution'])
    refresh = lua_string(prefs['refresh'])
    scale = lua_string(prefs['scale'] or 'auto')
    # Resolve each automatic field independently using this output's live modes.
    return f'''do
    local output, resolution, refresh = {output}, {resolution}, {refresh}
    local monitor = hl.get_monitor(output)
    local modes = monitor and monitor.available_modes or {{}}
    local preferred = modes[1]
    for _, mode in ipairs(modes) do
        if mode.preferred then preferred = mode; break end
    end
    if resolution == "" and refresh ~= "" and preferred then
        resolution = preferred.width .. "x" .. preferred.height
    end
    if resolution ~= "" and refresh == "" then
        local rate = nil
        for _, mode in ipairs(modes) do
            if resolution == mode.width .. "x" .. mode.height then
                rate = math.max(rate or 0, mode.refresh_rate)
            end
        end
        refresh = tostring(rate or (preferred and preferred.refresh_rate) or 60)
    end
    local mode = resolution == "" and "preferred" or resolution .. "@" .. refresh
    hl.monitor({{ output = output, mode = mode, scale = {scale} }})
end'''


def save(state):
    rules = ['-- Generated by Quickshell display settings.']
    rules.extend(monitor_rule(name, prefs) for name, prefs in state['monitors'].items())
    atomic(ROOT / 'monitors.lua', '\n'.join(rules) + '\n')
    atomic(ROOT / 'display.json', json.dumps(state))


def night(enabled, temperature):
    result = subprocess.run([HYPRCTL, 'hyprsunset', 'temperature', str(temperature)] if enabled
                            else [HYPRCTL, 'hyprsunset', 'identity'], capture_output=True, text=True)
    if result.returncode or any(word in result.stdout.lower() for word in ('error', 'failed', 'invalid')):
        raise RuntimeError(result.stderr or result.stdout)


def dispatch():
    state = read()
    command = sys.argv[1]
    if command == 'get':
        print(json.dumps(state))
    elif command == 'preview':
        result = subprocess.run([HYPRCTL, 'eval', monitor_rule(sys.argv[2], json.loads(sys.argv[3]))],
                                capture_output=True, text=True)
        print(result.stdout, end='')
        print(result.stderr, end='', file=sys.stderr)
        sys.exit(result.returncode)
    elif command == 'monitor':
        prefs = json.loads(sys.argv[3])
        state['monitors'][sys.argv[2]] = prefs
        save(state)
    elif command == 'night':
        enabled, temperature = sys.argv[2] == 'true', int(sys.argv[3])
        night(enabled, temperature)
        state['night'] = {'enabled': enabled, 'temperature': temperature}
        save(state)
    elif command == 'temperature':
        temperature = int(sys.argv[2])
        # Adjust an active night light, but only the toggle may enable it.
        if state['night']['enabled']:
            night(True, temperature)
        state['night']['temperature'] = temperature
        save(state)
    elif command == 'restore-night':
        prefs = state['night']
        for attempt in range(30):
            try:
                night(prefs['enabled'], prefs['temperature'])
                return
            except RuntimeError:
                if attempt == 29:
                    raise
                time.sleep(0.1)


def main():
    # Monitor and night-light requests can overlap; serialize read/modify/write
    # so one preference update cannot overwrite the other.
    ROOT.mkdir(parents=True, exist_ok=True)
    with (ROOT / 'display.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        dispatch()


if __name__ == '__main__':
    try:
        main()
    except (RuntimeError, OSError, ValueError) as error:
        print(error, file=sys.stderr)
        sys.exit(1)
